import { readFileSync } from "node:fs";
const s=readFileSync("docs/sql/G2A2_CARTEL_GUIDE_ATOMIC_BUDGET_CANDIDATE.sql","utf8");
const tests: Array<[string,boolean]> = [];
const check=(n:string,ok:boolean)=>tests.push([n,ok]);
const has=(r:RegExp)=>r.test(s);
const count=(r:RegExp)=>(s.match(r)??[]).length;
check("review only",has(/REVIEW ONLY; NEVER APPLIED/));
check("transaction",has(/^BEGIN;[\s\S]*COMMIT;/m));
check("three new tables only",count(/CREATE TABLE public\.cartel_guide_/g)===3);
check("no existing function changed",!has(/CREATE OR REPLACE FUNCTION/));
check("no existing table altered",!has(/ALTER TABLE public\.(?!cartel_guide_)/));
check("default disabled",has(/VALUES \(true, false, true, false\)/));
check("stop true by default",has(/emergency_stop boolean NOT NULL DEFAULT true/));
check("no seeded price quotes",!has(/INSERT INTO public\.cartel_guide_model_quotes/));
check("versioned price",has(/UNIQUE \(provider, model, price_version\)/));
check("bounded token caps",has(/max_input_tokens BETWEEN 1 AND 16000/) && has(/max_output_tokens BETWEEN 1 AND 4096/));
check("idempotency key",has(/UNIQUE \(user_id, workspace_id, request_id\)/));
check("RLS on three tables",count(/ALTER TABLE public\.cartel_guide_\w+ ENABLE ROW LEVEL SECURITY/g)===3);
check("no browser table privileges",count(/REVOKE ALL ON public\.cartel_guide_\w+ FROM PUBLIC, anon, authenticated/g)===3);
check("four new functions",count(/CREATE FUNCTION public\.cartel_guide_/g)===4);
check("fixed definer path",count(/SECURITY DEFINER SET search_path = pg_catalog, public/g)===4);
check("no browser RPC grants",count(/REVOKE ALL ON FUNCTION public\.cartel_guide_/g)===4);
check("service role only RPCs",count(/GRANT EXECUTE ON FUNCTION public\.cartel_guide_/g)===4);
check("all RPCs globally serialized",count(/pg_advisory_xact_lock\(4127, 2202\)/g)===4);
check("membership cross-tenant checks",has(/FROM public\.workspace_members m/) && has(/w\.owner_id = _user_id/));
check("duplicate request denied",has(/'DUPLICATE_REQUEST'/));
check("hard global day/month caps",has(/global_day_cap_micro_usd - v_global_day/) && has(/global_month_cap_micro_usd - v_global_month/));
check("platform concurrency cap",has(/v_pending >= v_cfg\.platform_concurrent_reservations/));
check("pending charges counted irrespective of period",has(/state IN \('held','in_flight'\) OR \(state = 'settled' AND reserved_at >= v_month\)/));
check("owner RPC",has(/has_platform_unrestricted_access\(_user_id\)/));
check("global ceiling ahead of owner bypass",s.indexOf("'GLOBAL_BUDGET_LIMIT'")<s.indexOf("v_owner := public.has_platform_unrestricted_access"));
check("customer pilot closed",has(/customer_pilot_enabled IS DISTINCT FROM true/));
check("explicit feature entitlement and commercial access",has(/e\.feature_key = 'guide_conversation'/) && has(/public\.evaluate_commercial_access/));
check("observe would_block denied",has(/v_eval->>'would_block' = 'true'/));
check("customer monthly ceilings and request cap",has(/customer_workspace_month_cap_micro_usd - v_workspace_month/) && has(/customer_user_month_cap_micro_usd - v_user_month/) && has(/v_user_requests >= v_cfg\.customer_user_month_requests/));
check("must mark before dispatch",has(/SET state='in_flight', started_at=now\(\)/));
check("release only before dispatch",has(/state='released', closed_at=now\(\)[\s\S]*state='held'/));
check("inflight only settlement",has(/IF v_row\.state <> 'in_flight' THEN/));
check("missing usage conservatively charged",has(/v_actual := v_row\.reserved_micro_usd/));
check("idempotent settlement",has(/IF v_row\.state = 'settled' THEN/));
check("overrun kills platform",has(/IF v_overrun THEN[\s\S]*SET emergency_stop=true/));
